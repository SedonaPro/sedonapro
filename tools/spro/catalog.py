"""spro catalog: docs/kits.md from kit.xml, kit.toml, profiles and the kit manifests.

    spro catalog            write docs/kits.md
    spro catalog --check    fail if docs/kits.md is out of date (CI)
"""
import re
import sys
import xml.etree.ElementTree as ET

from . import home as H
from . import project as P

OUT = P.ROOT / 'docs/kits.md'
DOMAINS = {
    'core': 'Sedona Framework core (Tridium)',
    'platform': 'Platforms',
    'base': 'Base libraries',
    'io': 'Inputs and outputs',
    'comm': 'Communication',
    'data': 'Data',
    'logic': 'Logic',
    'control': 'Control',
    'equip': 'Equipment',
    'alarm': 'Alarms',
    'sched': 'Schedules',
    'hvac': 'HVAC',
    'heat': 'Heating',
    'energy': 'Energy',
    'ui': 'User interface',
    'sim': 'Simulation',
}


def manifest(name):
    files = sorted((H.HOME / 'manifests' / name).glob(name + '-*.xml'), key=lambda p: p.stat().st_mtime)
    return ET.parse(files[-1]).getroot() if files else None


def native_id(kit):
    root = ET.parse(kit.dir / 'kit.xml').getroot()
    ids = {n.get('id').split('::')[0] for n in root.findall('native')}
    return ', '.join(sorted(ids))


def components(manifests):
    """{kit: [(type, [slot names])]} for concrete, palette-visible components."""
    types = {}
    for kit, m in manifests.items():
        for t in m.findall('type'):
            types['%s::%s' % (kit, t.get('name'))] = t
    def is_component(q):
        seen = set()
        while q and q not in seen:
            if q == 'sys::Component':
                return True
            seen.add(q)
            t = types.get(q)
            q = t.get('base') if t is not None else None
        return False
    def slots(q):
        t = types.get(q)
        if t is None or q == 'sys::Component':
            return []
        own = [s.get('name') for s in t.findall('slot') if 'a' not in (s.get('flags') or '')]
        return slots(t.get('base')) + own
    out = {}
    for kit, m in manifests.items():
        for t in m.findall('type'):
            if 'a' in (t.get('flags') or '') or not is_component(t.get('base')):
                continue
            pal = t.find("facets/bool[@name='palette']")
            if pal is not None and pal.get('val') == 'false':
                continue
            out.setdefault(kit, []).append((t.get('name'), slots('%s::%s' % (kit, t.get('name')))))
    return out


def render():
    H.compile_kits()
    known = P.kits()
    profiles = {p.stem: set(P.closure(P.load_toml(p)['kits'], known))
                for p in sorted((P.ROOT / 'profiles').glob('*.toml'))}
    mans = {n: m for n in known if (m := manifest(n)) is not None}
    comps = components(mans)
    by = {}
    for k in known.values():
        by.setdefault(k.domain, []).append(k)
    order = [d for d in DOMAINS if d in by] + sorted(d for d in by if d not in DOMAINS)

    L = ['# Kits', '',
         '<!-- generated by ./spro catalog from kit.xml, kit.toml, profiles/ and the kit manifests -->', '',
         'Targets: `linux` — Linux controller, `sim` — ESP32 firmware code on a PC, `esp32` — ESP32-S3.',
         'Profiles: %s. A kit outside a profile is added with `--add kit`.' % ', '.join(
             '`%s`' % p for p in profiles), 'Native ids: `registry/native-ids.md`.', '']
    packs = P.packs()
    if packs:
        L += ['## Packs', '', 'Kit sets for a trade, added to a profile with `--pack NAME` '
              '(rules of the pro kits: [pro-kits.md](pro-kits.md)).', '',
              '| Pack | Kits | Summary |', '|---|---|---|']
        for name, pk in packs.items():
            L.append('| `%s` | %s | %s |' % (name, ', '.join('[%s](#%s)' % (k, k.lower()) for k in pk['kits']),
                                          pk.get('summary', '')))
        L.append('')
    head = '| Kit | Targets | %s | Native | Summary |' % ' | '.join(profiles)
    for dom in order:
        L += ['## %s' % DOMAINS.get(dom, dom), '', head, '|---|---|%s---|---|' % ('---|' * len(profiles))]
        for k in sorted(by[dom], key=lambda k: k.name.lower()):
            prof = ' | '.join('✓' if k.name in profiles[p] else '' for p in profiles)
            summary = re.sub(r'\s+', ' ', k.summary).replace('|', '\\|')
            L.append('| [%s](#%s) | %s | %s | %s | %s |' % (
                k.name, k.name.lower(), ' '.join(k.targets), prof, native_id(k) if k.natives else '', summary))
        L.append('')
    L += ['## Components', '']
    for dom in order:
        for k in sorted(by[dom], key=lambda k: k.name.lower()):
            L.append('### %s' % k.name)
            L.append('')
            readme = k.dir / 'README.md'
            src = '`%s`' % k.rel.as_posix() + (', [README](../%s)' % readme.relative_to(P.ROOT).as_posix()
                                               if readme.exists() else '')
            deps = ', '.join(k.depends) or '—'
            L.append('%s · depends on %s' % (src, deps))
            L.append('')
            widgets = sorted(p.name[:-len('.widget.json')] for p in (k.dir / 'ui').glob('*.widget.json'))
            if widgets:
                L += ['Widgets ([widgets.md](widgets.md)): %s' % ', '.join('`%s`' % w for w in widgets), '']
            if k.name not in mans:
                L += ['(not compiled)', '']
                continue
            items = comps.get(k.name, [])
            if not items:
                L += ['No palette components (library or service kit).', '']
                continue
            L += ['| Component | Slots |', '|---|---|']
            for name, slots in sorted(items):
                L.append('| %s | %s |' % (name, ', '.join(slots) or '—'))
            L.append('')
    return '\n'.join(L).rstrip('\n') + '\n'


def catalog(check=False):
    text = render()
    if check:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit('docs/kits.md is out of date: run ./spro catalog')
        print('docs/kits.md up to date')
        return 0
    OUT.write_text(text)
    print('wrote', OUT.relative_to(P.ROOT))
    return 0
