"""Boards: boards/<name>.toml -> channel table (spro_board.c) for kit sproHal.

    name    = "my-board"
    title   = "My controller"
    hal     = "sim" | "linux-gpiod" | "linux-sysfs" | "esp32"
    targets = ["linux"]
    [defaults]                       # optional, merged into every channel
    dev = "gpiochip0"
    [channels]
    DI1 = { kind = "di", pin = 17, pull = "up", invert = true }
    DO1 = { kind = "do", pin = 5, initial = 0 }
    AI1 = { kind = "ai", pin = 1, raw_max = 4095, range = [0.0, 10.0], unit = "V" }
    AO1 = { kind = "ao", pin = 14, pwm_hz = 1000, range = [0.0, 100.0] }

Porting to a new device = a new board file (./spro board new NAME --from rpi4);
C code is needed only for a new kind of hardware access (a new hal backend).
"""
import re

from .project import ROOT, load_toml

BOARDS = ROOT / 'boards'
HAL = '/repo/kits/io/sproHal/backends/'
BACKENDS = {  # hal -> (native source dirs, targets)
    'sim':         ([HAL + 'sim'], ('linux', 'sim')),
    'linux-gpiod': ([HAL + 'linux-gpiod', HAL + 'linux-common'], ('linux',)),
    'linux-sysfs': ([HAL + 'linux-sysfs', HAL + 'linux-common'], ('linux',)),
    'esp32':       ([HAL + 'esp32'], ('esp32',)),
}
KINDS = {'di': 1, 'do': 2, 'ai': 3, 'ao': 4}
PULLS = {'none': 0, 'up': 1, 'down': 2}
KEYS = {'kind', 'pin', 'dev', 'pull', 'invert', 'raw_max', 'range', 'unit', 'pwm_hz', 'initial', 'note'}
NAME_RE = re.compile(r'^[A-Za-z][A-Za-z0-9_]{0,14}$')   # fits HalPoint.channel (Buf 16)


def names():
    return sorted(p.stem for p in BOARDS.glob('*.toml'))


def load(name):
    path = BOARDS / (name + '.toml')
    if not path.exists():
        raise SystemExit('no board %s (boards/: %s)' % (name, ', '.join(names())))
    b = load_toml(path)
    errors = []
    hal = b.get('hal')
    if hal not in BACKENDS:
        errors.append('hal must be one of %s' % ', '.join(BACKENDS))
    defaults = b.get('defaults', {})
    chans = []
    for cname, ch in b.get('channels', {}).items():
        c = dict(defaults, **ch)
        where = '%s: channel %s' % (path.name, cname)
        if not NAME_RE.match(cname):
            errors.append('%s: name must be a letter + up to 14 letters/digits/_' % where)
        for k in set(c) - KEYS:
            errors.append('%s: unknown key %r' % (where, k))
        kind = c.get('kind')
        if kind not in KINDS:
            errors.append('%s: kind must be di, do, ai or ao' % where)
            continue
        if hal in ('esp32', 'linux-gpiod', 'linux-sysfs') and kind != 'ai' and 'pin' not in c:
            errors.append('%s: pin is required' % where)
        if hal == 'esp32' and kind == 'ai' and 'pin' not in c:
            errors.append('%s: pin is required' % where)
        if hal.startswith('linux') and kind == 'ai' and 'dev' not in c:
            errors.append('%s: dev (IIO file) is required' % where)
        if c.get('pull', 'none') not in PULLS:
            errors.append('%s: pull must be up, down or none' % where)
        lo, hi = c.get('range', [0.0, 100.0] if kind == 'ao' else [0.0, 0.0])
        raw_max = c.get('raw_max', 4095 if hal == 'esp32' and kind == 'ai' else 0)
        if kind == 'ai' and hal == 'sim' and raw_max == 0:
            raw_max = 10000      # sim inputs: fine steps over the range
        chans.append(dict(name=cname, kind=KINDS[kind], invert=int(bool(c.get('invert', False))),
                          pull=PULLS[c.get('pull', 'none')], pin=int(c.get('pin', -1)),
                          dev=c.get('dev'), raw_max=float(raw_max), lo=float(lo), hi=float(hi),
                          pwm_hz=int(c.get('pwm_hz', 0)), initial=float(c.get('initial', 0))))
    serial = b.get('serial', [])
    if not isinstance(serial, list) or not all(isinstance(x, str) and x.startswith('/dev/') for x in serial):
        errors.append('%s: serial must be a list of /dev/... names' % path.name)
        serial = []
    if not chans and not serial:
        errors.append('%s: no channels and no serial ports' % path.name)
    if len({c['name'] for c in chans}) != len(chans):
        errors.append('%s: duplicate channel names' % path.name)
    if errors:
        raise SystemExit('board %s:\n  %s' % (name, '\n  '.join(errors)))
    b['channel_list'] = chans
    b['serial_list'] = serial
    return b


def check_target(board, target):
    targets = board.get('targets', BACKENDS[board['hal']][1])
    if target not in targets or target not in BACKENDS[board['hal']][1]:
        raise SystemExit('board %s (hal %s) is not for target %s' % (board['name'], board['hal'], target))


def sources(board):
    return BACKENDS[board['hal']][0]


def cstr(s):
    return 'NULL' if s is None else '"%s"' % s.replace('\\', '\\\\').replace('"', '\\"')


def write_c(board, native_dir):
    lines = ['// generated by ./spro from boards/%s.toml: do not edit' % board['name'],
             '#include "spro_hal.h"', '#include <stddef.h>', '',
             'const char* const spro_board_name = %s;' % cstr(board['name']), '',
             'const spro_channel_t spro_board_channels[] = {']
    for c in board['channel_list']:
        f = lambda x: repr(float(x)) + 'f'
        lines.append('  { %s, %d, %d, %d, %d, %s, %s, %s, %s, %du, %s },' % (
            cstr(c['name']), c['kind'], c['invert'], c['pull'], c['pin'], cstr(c['dev']),
            f(c['raw_max']), f(c['lo']), f(c['hi']), c['pwm_hz'], f(c['initial'])))
    if not board['channel_list']:
        lines.append('  { NULL }')
    lines += ['};', '',
              'const int spro_board_channel_count = %d;' % len(board['channel_list']), '',
              '// serial ports, Modbus/serial port number = index + 1',
              'const char* const spro_board_serial[] = { %s };' % ', '.join(
                  [cstr(x) for x in board['serial_list']] or ['NULL']),
              'const int spro_board_serial_count = %d;' % len(board['serial_list']), '']
    (native_dir / 'spro_board.c').write_text('\n'.join(lines))


def describe():
    for n in names():
        b = load(n)
        kinds = {}
        for c in b['channel_list']:
            kinds[c['kind']] = kinds.get(c['kind'], 0) + 1
        inv = {v: k for k, v in KINDS.items()}
        print('%-20s %-12s %-14s %s  [%s]' % (n, b['hal'], '+'.join(b.get('targets', [])),
                                              b.get('title', ''),
                                              ' '.join('%d %s' % (v, inv[k]) for k, v in sorted(kinds.items()))))


def new(name, template):
    dst = BOARDS / (name + '.toml')
    if dst.exists():
        raise SystemExit('%s exists' % dst)
    src = (BOARDS / (template + '.toml')).read_text()
    src = re.sub(r'^name\s*=.*$', 'name    = "%s"' % name, src, count=1, flags=re.M)
    src = re.sub(r'^title\s*=.*$', 'title   = "%s (from %s)"' % (name, template), src, count=1, flags=re.M)
    dst.write_text(src)
    load(name)
    print('created %s: edit pins, then ./spro build <target> --board %s' % (dst.relative_to(ROOT), name))
